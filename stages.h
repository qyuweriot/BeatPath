#pragma once
#include <utility>
#include <vector>

// ------------------------------------------------------------
// タイル定数
// ------------------------------------------------------------
enum TileType {
    T_EMPTY = 0,
    T_TURN_R, T_TURN_L,      // 方向転換
    T_SPLIT, T_SPLIT3,       // 分裂
    T_SPEED2,                // 次の1拍2マス先へジャンプ
    T_STOP,                  // 1拍停止
    T_PAINT_R, T_PAINT_B, T_PAINT_Y, // 色変更 (音色も変わる)
    T_COUNT
};

// ------------------------------------------------------------
// ステージ定義型
// ------------------------------------------------------------
struct StartDef { int x, y, dx, dy; };
struct GoalDef  { int x, y; int color; };       // color -1 = 何色でもOK
struct WarpDef  { int x1, y1, x2, y2; };        // 双方向ワープ

struct StageDef {
    const char* name;
    int bpm, beatsPM;
    std::vector<StartDef> starts;
    std::vector<GoalDef>  goals;
    std::vector<WarpDef>  warps;
    std::vector<std::pair<TileType, int>> inv;
    int gridW = 0, gridH = 0;   // 0 = beatpath.cfg の値を使用
};

// ------------------------------------------------------------
// ステージ定義の書き方
// ------------------------------------------------------------
// makeStages() の return { ... } の末尾に StageDef を追記する。
//
// { "名前", bpm, beatsPM,
//   /* starts */ {{x,y,dx,dy}, ...},    // ボール初期位置・方向 (dx/dy = ±1)
//   /* goals  */ {{x,y,color}, ...},    // ゴール位置・要求色 (-1=任意色)
//   /* warps  */ {{x1,y1,x2,y2}, ...},  // ワープペア (双方向)
//   /* inv    */ {{タイル種別,個数},...}, // 手持ちタイル
//   gridW, gridH },                     // グリッドサイズ (0,0 = beatpath.cfg の値)
//
// タイル種別: T_TURN_R / T_TURN_L   右折・左折
//             T_SPLIT  / T_SPLIT3   2分裂・3分裂
//             T_SPEED2              次の1拍2マス先へジャンプ
//             T_STOP                1拍停止
//             T_PAINT_R / B / Y     赤・青・黄に色変更
// ------------------------------------------------------------

// ------------------------------------------------------------
// ビルトインステージ (8ステージ)
// 新しいステージは } の直前に追記する
// ------------------------------------------------------------
inline std::vector<StageDef> makeStages() {
    return {
        // 1: チュートリアル - 曲がる
        { "FIRST STEPS", 112, 4,
          {{0,0,1,0}}, {{1,1,-1}}, {},
          {{T_TURN_R,2}},
          4, 3 },
        // 2: 分裂で2つのゴールへ同時到達
        { "SPLIT", 116, 4,
          {{0,2,1,0}}, {{2,0,-1},{3,3,-1}}, {},
          {{T_SPLIT,1},{T_TURN_L,1}},
          5, 4 },
        // 3: 加速
        { "SPEED", 124, 4,
          {{0,2,1,0}}, {{4,1,-1},{2,4,-1}},
          {},
          {{T_SPLIT,1},{T_TURN_R,1},{T_TURN_L,1},{T_SPEED2,1}},
          6, 6 },
        // 4: 三分裂で3ゴール
        { "TRIPLE", 120, 6,
          {{0,3,1,0}}, {{3,1,-1},{4,3,-1},{3,5,-1}}, {},
          {{T_SPLIT3,1},{T_TURN_R,1},{T_TURN_L,1},{T_STOP,2}},
          5, 7 },
        // 5: ワープ (入口と出口のセット)
        { "WARP", 122, 4,
          {{0,1,1,0}}, {{3,3,-1}},
          {{1,2, 3,1}},
          {{T_TURN_R,1}},
          5, 5 },
        // 6: 色ギミック - ペイントして同色ゴールへ
        { "COLORS", 140, 6,
          {{0,2,1,0}}, {{3,1,0},{3,5,1}}, {},
          {{T_SPLIT,1},{T_TURN_R,1},{T_TURN_L,1},{T_PAINT_R,1},{T_PAINT_B,1}},
          6, 7 },
        // 7: 複数スタート + 5ゴール
        { "DUET", 126, 8,
          {{0,2,1,0},{0,4,1,0}}, {{4,0,-1},{4,6,-1},{6,1,-1},{6,3,-1},{6,5,-1}}, {},
          {{T_SPLIT,1},{T_SPLIT3,1},{T_TURN_R,3},{T_TURN_L,4},{T_SPEED2,1},{T_STOP,1}},
          8, 7 },
        // 8: 総決算 - ワープ + 色 + 速度系のおまけ付き
        { "FINALE", 128, 8,
          {{0,3,1,0}}, {{4,2,0},{5,3,1},{4,4,2}},
          {{2,1, 4,3}},
          {{T_SPLIT,2},{T_TURN_R,2},{T_TURN_L,4},
           {T_PAINT_R,1},{T_PAINT_B,1},{T_PAINT_Y,1},{T_SPEED2,1},{T_STOP,1}},
          6, 7 },
    };
}
